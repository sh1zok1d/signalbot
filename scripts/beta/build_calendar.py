"""Generate config/beta_calendar.yaml from first-party schedule pages already in the repository.

    python -m scripts.beta.build_calendar [--out config/beta_calendar.yaml]

Sources (no network):
- CPI 2020-2024: docs/research_data/BLS_CPI_RELEASE_SCHEDULE_ARCHIVE_V0/EVENTS.json
  (point-in-time BLS schedule, SCHEDULED_RELEASE_UTC);
- CPI Dec 2025 - Dec 2026: the BLS schedule page captured live in the same dataset (raw/live);
- FOMC 2020-2024: docs/research_data/D11_FOMC_OFFICIAL_V0/PIN.json (statement times);
- FOMC 2025-2027: the Federal Reserve calendar page captured in the same dataset
  (raw/fomccalendars.htm); the statement is at 14:00 America/New_York on the last meeting day.

The output is deterministic. Add NFP, PCE or other releases by hand below `events:` with the
same fields; the product reads any `kind`.
"""
from __future__ import annotations

import argparse
import html
import json
import re
from datetime import date, datetime, time, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[2]
BLS = ROOT / "docs/research_data/BLS_CPI_RELEASE_SCHEDULE_ARCHIVE_V0"
FOMC = ROOT / "docs/research_data/D11_FOMC_OFFICIAL_V0"
NY = ZoneInfo("America/New_York")
MONTHS = {m: i for i, m in enumerate(("january", "february", "march", "april", "may", "june", "july",
                                      "august", "september", "october", "november", "december"), 1)}
BLS_MONTHS = {"jan": 1, "feb": 2, "mar": 3, "apr": 4, "may": 5, "jun": 6, "june": 6, "jul": 7, "july": 7,
              "aug": 8, "sep": 9, "sept": 9, "oct": 10, "nov": 11, "dec": 12}


def _utc(d: date, hh: int, mm: int) -> str:
    local = datetime.combine(d, time(hh, mm), tzinfo=NY)
    return local.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def cpi_events() -> list:
    out = {}
    for e in json.loads((BLS / "EVENTS.json").read_text())["EVENTS"]:
        out[e["SCHEDULED_RELEASE_UTC"]] = "bls_schedule_archive_2020_2024"
    for f in sorted((BLS / "raw/live").glob("*.bin")):
        text = f.read_bytes().decode("utf-8", "ignore")
        if "Schedule of Releases for the Consumer Price Index" not in text:
            continue
        for mon, day, year, hh, mm, ap in re.findall(
                r"<td>([A-Z][a-z]+)\.?\s+(\d{1,2}),\s+(20\d\d)</td>\s*<td>(\d\d):(\d\d)\s*(AM|PM)</td>", text):
            m = BLS_MONTHS[mon.lower()]
            h = int(hh) % 12 + (12 if ap == "PM" else 0)
            out.setdefault(_utc(date(int(year), m, int(day)), h, int(mm)), "bls_schedule_page_live_capture")
    return [{"kind": "CPI", "at_utc": k, "source": v} for k, v in sorted(out.items())]


def fomc_events() -> list:
    out = {}
    for e in json.loads((FOMC / "PIN.json").read_text())["EVENTS"]:
        out[e["ANNOUNCEMENT_UTC"]] = "federal_reserve_statements_2020_2024"
    text = html.unescape((FOMC / "raw/fomccalendars.htm").read_text(encoding="utf-8", errors="ignore"))
    parts = re.split(r"(20\d\d) FOMC Meetings", text)
    for k in range(1, len(parts) - 1, 2):
        year, seg = int(parts[k]), parts[k + 1]
        if year < 2025:
            continue
        months = re.findall(r"fomc-meeting__month[^>]*>\s*<strong>([^<]+)</strong>", seg)
        dates = re.findall(r"fomc-meeting__date[^>]*>([^<]+)<", seg)
        for mon, ds in zip(months, dates):
            if "notation" in ds.lower() or "unscheduled" in ds.lower():
                continue
            mons = [MONTHS[x.strip().lower()] for x in mon.split("/")]
            days = [int(x) for x in re.findall(r"\d+", ds.split("(")[0])]
            if not days:
                continue
            d = date(year, mons[-1], days[-1])
            out.setdefault(_utc(d, 14, 0), "federal_reserve_calendar_page_capture")
    return [{"kind": "FOMC", "at_utc": k, "source": v} for k, v in sorted(out.items())]


def render(events: list) -> str:
    lines = [
        "# Signalbot beta event calendar (PRODUCT_DECISION_V2 §2.3). Generated by",
        "# scripts/beta/build_calendar.py from first-party schedule pages in the repository;",
        "# extend `events:` by hand (same fields) for NFP, PCE or rescheduled releases.",
        "# Times are UTC. `kind` drives the text and the event-day statistics.",
        "version: BETA_CALENDAR_V1",
        "recurring:",
        "  options_expiry:            # Deribit BTC options: every Friday 08:00 UTC",
        "    weekday: 4",
        '    time_utc: "08:00"',
        "    monthly: last_friday",
        "    quarterly_months: [3, 6, 9, 12]",
        '  funding_utc: ["00:00", "08:00", "16:00"]   # Binance USD-M BTCUSDT funding settlements',
        "events:",
    ]
    for e in events:
        lines.append(f'  - {{kind: {e["kind"]}, at_utc: "{e["at_utc"]}", source: {e["source"]}}}')
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(ROOT / "config/beta_calendar.yaml"))
    args = ap.parse_args(argv)
    events = sorted(cpi_events() + fomc_events(), key=lambda e: (e["at_utc"], e["kind"]))
    Path(args.out).write_text(render(events), encoding="utf-8")
    print(f"wrote {len(events)} events to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
